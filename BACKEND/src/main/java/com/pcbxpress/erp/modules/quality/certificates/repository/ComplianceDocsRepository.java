    // Find by order number and status with pagination
    Page<ComplianceDocs> findByOrderNoAndStatus(String orderNo, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by customer and status
    List<ComplianceDocs> findByCustomerAndStatus(String customer, ComplianceDocs.Status status);
    
    // Find by customer and status with pagination
    Page<ComplianceDocs> findByCustomerAndStatus(String customer, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by lot number and status
    List<ComplianceDocs> findByLotNoAndStatus(String lotNo, ComplianceDocs.Status status);
    
    // Find by lot number and status with pagination
    Page<ComplianceDocs> findByLotNoAndStatus(String lotNo, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by work order number and status
    List<ComplianceDocs> findByWorkOrderNoAndStatus(String workOrderNo, ComplianceDocs.Status status);
    
    // Find by work order number and status with pagination
    Page<ComplianceDocs> findByWorkOrderNoAndStatus(String workOrderNo, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by shipment ID and status
    List<ComplianceDocs> findByShipmentIdAndStatus(String shipmentId, ComplianceDocs.Status status);
    
    // Find by shipment ID and status with pagination
    Page<ComplianceDocs> findByShipmentIdAndStatus(String shipmentId, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by generated by user
    List<ComplianceDocs> findByGeneratedBy(String generatedBy);
    
    // Find by generated by user with pagination
    Page<ComplianceDocs> findByGeneratedBy(String generatedBy, Pageable pageable);
    
    // Find by sent to user
    List<ComplianceDocs> findBySentTo(String sentTo);
    
    // Find by sent to user with pagination
    Page<ComplianceDocs> findBySentTo(String sentTo, Pageable pageable);
    
    // Find by generated by user and status
    List<ComplianceDocs> findByGeneratedByAndStatus(String generatedBy, ComplianceDocs.Status status);
    
    // Find by sent to user and status
    List<ComplianceDocs> findBySentToAndStatus(String sentTo, ComplianceDocs.Status status);
    
    // Find by carrier
    List<ComplianceDocs> findByCarrier(String carrier);
    
    // Find by carrier with pagination
    Page<ComplianceDocs> findByCarrier(String carrier, Pageable pageable);
    
    // Find by carrier and status
    List<ComplianceDocs> findByCarrierAndStatus(String carrier, ComplianceDocs.Status status);
    
    // Find by carrier and status with pagination
    Page<ComplianceDocs> findByCarrierAndStatus(String carrier, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by AWB
    List<ComplianceDocs> findByAwb(String awb);
    
    // Find by AWB with pagination
    Page<ComplianceDocs> findByAwb(String awb, Pageable pageable);
    
    // Find by AWB and status
    List<ComplianceDocs> findByAwbAndStatus(String awb, ComplianceDocs.Status status);
    
    // Find by AWB and status with pagination
    Page<ComplianceDocs> findByAwbAndStatus(String awb, ComplianceDocs.Status status, Pageable pageable);
    
    // Find by ship date
    List<ComplianceDocs> findByShipDate(LocalDateTime shipDate);
    
    // Find by ship date with pagination
    Page<ComplianceDocs> findByShipDate(LocalDateTime shipDate, Pageable pageable);
    
    // Find by ship date range
    List<ComplianceDocs> findByShipDateBetween(LocalDateTime startDate, LocalDateTime endDate);
    
    // Find by ship date range with pagination
    Page<ComplianceDocs> findByShipDateBetween(LocalDateTime startDate, LocalDateTime endDate, Pageable pageable);
    
    // Find by ship date range and status
    List<ComplianceDocs> findByShipDateBetweenAndStatus(LocalDateTime startDate, LocalDateTime endDate, ComplianceDocs.Status status);
    
    // Find by ship date range and status with pagination
    Page<ComplianceDocs> findByShipDateBetweenAndStatus(LocalDateTime startDate, LocalDateTime endDate, ComplianceDocs.Status status, Pageable pageable);
    
    // Compliance Docs specific queries
    // Find by document type
    List<ComplianceDocs> findByDocumentType(String documentType);
    
    // Find by document type with pagination
    Page<ComplianceDocs> findByDocumentType(String documentType, Pageable pageable);
    
    // Find by document title
    List<ComplianceDocs> findByDocumentTitle(String documentTitle);
    
    // Find by document title with pagination
    Page<ComplianceDocs> findByDocumentTitle(String documentTitle, Pageable pageable);
    
    // Find by document version
    List<ComplianceDocs> findByDocumentVersion(String documentVersion);
    
    // Find by document version with pagination
    Page<ComplianceDocs> findByDocumentVersion(String documentVersion, Pageable pageable);
    
    // Find by document author
    List<ComplianceDocs> findByDocumentAuthor(String documentAuthor);
    
    // Find by document author with pagination
    Page<ComplianceDocs> findByDocumentAuthor(String documentAuthor, Pageable pageable);
    
    // Find by document approver
    List<ComplianceDocs> findByDocumentApprover(String documentApprover);
    
    // Find by document approver with pagination
    Page<ComplianceDocs> findByDocumentApprover(String documentApprover, Pageable pageable);
    
    // Find by compliance standard
