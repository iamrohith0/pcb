    // Count compliance documents by compliance status
    long countByComplianceStatus(String complianceStatus);
    
    // Count compliance documents by is public
    long countByIsPublic(Boolean isPublic);
    
    // Count compliance documents by is archived
    long countByIsArchived(Boolean isArchived);
    
    // Find the latest document number for generating new ones
    @Query("SELECT MAX(c.documentNo) FROM ComplianceDocs c WHERE c.documentNo LIKE :prefix%")
    String findLatestDocumentNoByPrefix(@Param("prefix") String prefix);
